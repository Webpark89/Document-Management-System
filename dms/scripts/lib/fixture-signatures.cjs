const { PDFDocument } = require("pdf-lib");

// Fixtures must use the same registered image format as production approvals.
async function registeredSignature(user, encryption) {
  if (!user?.signature_encrypted)
    throw Error(`Missing registered signature: ${user?.id}`);
  const uri = encryption.decrypt(user.signature_encrypted);
  const match = uri.match(
    /^data:(image\/(?:png|jpeg));base64,([A-Za-z0-9+/=\s]+)$/,
  );
  if (!match) throw Error(`Invalid registered signature: ${user.id}`);
  const pdf = await PDFDocument.create();
  const bytes = Buffer.from(match[2], "base64");
  const image =
    match[1] === "image/png"
      ? await pdf.embedPng(bytes)
      : await pdf.embedJpg(bytes);
  if (image.width < 2 || image.height < 2)
    throw Error(`Empty signature image: ${user.id}`);
  return user.signature_encrypted;
}

const escapeHtml = (value) =>
  String(value ?? "").replace(
    /[&<>"']/g,
    (c) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[c],
  );

